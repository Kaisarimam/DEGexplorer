# =============================================================================
# analysis_ui.R -- the Analysis tab: run differential expression from raw counts
# =============================================================================

#' Sidebar block shown while the Analysis tab is open.
analysis_sidebar_ui <- function() {
  tagList(
    h4("Analysis settings", class = "section"),
    selectInput("a_engine", "Engine", choices = DE_ENGINES),
    uiOutput("a_engine_note"),
    radioButtons("a_level", "Analysis", inline = FALSE,
                 choices = c("Gene expression (DGE)" = "gene",
                             "Transcript expression (DTE)" = "transcript",
                             "Transcript usage (DTU)" = "dtu")),
    conditionalPanel("input.a_level == 'transcript'",
      tags$details(open = NA,
        tags$summary(tags$strong("Transcript-level settings")),
        div(class = "ctl-block",
          uiOutput("a_tx_sop"),
          conditionalPanel("input.a_engine == 'limma' || input.a_engine == 'edger'",
            checkboxInput("a_divide_od", "Divide counts by quantification overdispersion (recommended)", TRUE),
            helpText(style = "font-size:.82em",
              "Removes the extra variance from reads that fit several isoforms (edgeR divided counts,",
              "Baldoni et al. 2024). Needs Salmon / kallisto folders quantified with Gibbs or bootstrap resamples.")),
          conditionalPanel("input.a_engine == 'ebseq'",
            radioButtons("a_ebseq_ng", "Ng vector (isoform uncertainty groups)",
                         choices = c("Isoforms per gene (GetNg)" = "isoforms",
                                     "From a file (rsem-generate-ngvector)" = "file",
                                     "None (treat like genes)" = "none")),
            conditionalPanel("input.a_ebseq_ng == 'isoforms'",
              numericInput("a_ebseq_trunthre", "Groups (GetNg TrunThre)", 3, min = 2, max = 10, step = 1),
              helpText(style = "font-size:.82em", "Transcripts of genes with 1, 2 or 3+ isoforms form three groups with their own variance, as EBSeq recommends.")),
            conditionalPanel("input.a_ebseq_ng == 'file'",
              fileInput("a_ngvec", NULL, accept = c(".ngvec", ".txt", ".tsv")),
              helpText(style = "font-size:.82em", "One Ng per transcript: rsem-generate-ngvector's output (in the count matrix's row order), or two columns (transcript, Ng). Best for de novo transcriptomes.")))))),
    conditionalPanel("input.a_level == 'dtu'",
      tags$details(open = NA,
        tags$summary(tags$strong("Transcript-usage settings")),
        div(class = "ctl-block",
          uiOutput("a_dtu_sop"),
          selectInput("a_dtu_counts", "Counts",
                      choices = c("Recommended for the method" = "auto",
                                  "Divided by quantification overdispersion" = "divided",
                                  "scaledTPM" = "scaledTPM", "dtuScaledTPM" = "dtuScaledTPM",
                                  "Estimated counts as they are" = "estimated")),
          selectInput("a_dtu_filter", "Filter",
                      choices = c("Recommended for the method" = "auto",
                                  "DRIMSeq dmFilter (Love et al. 2018)" = "drimseq",
                                  "edgeR filterByExpr" = "edger")),
          uiOutput("a_dtu_filter_note"),
          conditionalPanel("input.a_dtu_filter == 'drimseq' || (input.a_dtu_filter == 'auto' && (input.a_engine == 'dexseq' || input.a_engine == 'drimseq'))",
            fluidRow(
              column(4, numericInput("a_dtu_min_gene", "Gene count", 10, min = 0, step = 1)),
              column(4, numericInput("a_dtu_min_tx", "Transcript count", 10, min = 0, step = 1)),
              column(4, numericInput("a_dtu_min_prop", "Share", 0.1, min = 0, max = 1, step = 0.05))),
            helpText(style = "font-size:.82em", "Gene count in every sample; transcript count and share of its gene in at least the smallest group's number of samples.")),
          conditionalPanel("input.a_engine == 'edger_dtu' || input.a_engine == 'limma_dtu'",
            radioButtons("a_dtu_gene_test", "Gene-level test",
                         choices = c("Simes (most powerful when one transcript changes)" = "simes",
                                     "F-test (several transcripts switching)" = "F")),
            checkboxInput("a_dtu_robust", "Robust empirical Bayes", TRUE)),
          conditionalPanel("input.a_engine == 'drimseq'",
            numericInput("a_drimseq_sd", "Post-hoc filter: minimum SD of a transcript's share (0 = off)", 0.1,
                         min = 0, max = 0.5, step = 0.01)),
          conditionalPanel("input.a_engine == 'saturn'",
            radioButtons("a_saturn_p", "satuRn p-values",
                         choices = c("Empirical (recommended)" = "empirical", "Regular" = "regular")))))),
    conditionalPanel("input.a_level != 'gene' && input.a_engine != 'ebseq'",
      checkboxInput("a_stager", "Stage-wise testing (stageR): gene-level FDR, then transcripts", TRUE),
      numericInput("a_stager_alpha", "Stage-wise alpha", 0.05, min = 0.001, max = 0.5, step = 0.01),
      uiOutput("a_stager_note")),
    actionButton("a_recommended", "Use recommended settings",
                 class = "btn-sm btn-block"),
    uiOutput("a_recommended_help"),

    conditionalPanel("input.a_level != 'dtu'", tags$details(open = NA,
      tags$summary(tags$strong("Filtering")),
      div(class = "ctl-block",
        helpText("Keep a gene when enough samples reach a minimum abundance."),
        numericInput("a_min_abundance", "Minimum abundance", 10, min = 0, step = 1),
        checkboxInput("a_use_cpm", "Measure abundance as CPM, not raw counts", FALSE),
        radioButtons("a_filter_mode", "In at least",
                     choices = c("the smallest group of the main variable" = "group",
                                 "a number of samples" = "samples",
                                 "a proportion of samples" = "proportion"),
                     selected = "group"),
        conditionalPanel("input.a_filter_mode == 'samples'",
          numericInput("a_min_samples", "Number of samples", 2, min = 1, step = 1)),
        conditionalPanel("input.a_filter_mode == 'proportion'",
          sliderInput("a_min_proportion", "Proportion of samples", 0.05, 1, 0.5, step = 0.05))))),

    conditionalPanel("input.a_engine == 'deseq2'",
      tags$details(
        tags$summary(tags$strong("DESeq2 options")),
        div(class = "ctl-block",
          selectInput("a_fit_type", "Dispersion fit", c("parametric", "local", "mean")),
          numericInput("a_alpha", "Target FDR for independent filtering (alpha)", 0.1,
                       min = 0.001, max = 0.5, step = 0.01),
          numericInput("a_lfc_threshold", "Test against |log2 FC| threshold", 0, min = 0, step = 0.1),
          checkboxInput("a_indep", "Independent filtering", TRUE),
          checkboxInput("a_cooks", "Cook's distance outlier filtering", TRUE),
          radioButtons("a_deseq2_test", "Test",
                       choices = c("Wald (per comparison)" = "wald",
                                   "Likelihood-ratio (drop the main variable)" = "lrt")),
          selectInput("a_shrink", "Fold-change shrinkage (lfcShrink)",
                      choices = c("none" = "none", "ashr (recommended)" = "ashr",
                                  "apeglm" = "apeglm", "normal" = "normal")),
          helpText("Shrinkage pulls noisy fold changes of low-count genes towards 0 for ranking and plots; p-values are unchanged and the raw estimates are kept as log2FoldChange_mle."),
          uiOutput("a_shrink_note"),
          radioButtons("a_transform", "Transform for PCA / heatmaps", inline = TRUE,
                       choices = c("VST" = "vst", "rlog" = "rlog")),
          checkboxInput("a_blind", "Blind transform (ignore the design)", TRUE)))),

    conditionalPanel("input.a_engine == 'deseq2' || input.a_engine == 'edger'",
      checkboxInput("a_length_offset", "Gene-length offsets (sample-specific lengths)", FALSE),
      uiOutput("a_offset_note")),

    conditionalPanel("input.a_engine == 'limma' || input.a_engine == 'edger'",
      selectInput("a_norm_method", "Normalisation (edgeR TMM and others)",
                  choices = c("TMM", "TMMwsp", "upperquartile", "RLE", "none"))),

    conditionalPanel("input.a_engine == 'limma'",
      tags$details(
        tags$summary(tags$strong("limma-voom options")),
        div(class = "ctl-block",
          radioButtons("a_limma_voom", NULL,
                       choices = c("voom" = "voom", "voom with sample quality weights" = "quality")),
          checkboxInput("a_limma_trend", "eBayes trend (intensity-dependent prior)", FALSE),
          checkboxInput("a_limma_robust", "Robust eBayes (protect against outlier genes)", FALSE),
          selectInput("a_limma_block", "Random block (duplicateCorrelation)", choices = c("(none)")),
          helpText("Models a ticked covariate (e.g. donor) as a random effect instead of a fixed one. Slower, and with fewer than ~5 blocks a fixed covariate is usually the better choice."),
          numericInput("a_limma_lfc", "Test against |log2 FC| threshold (treat)", 0, min = 0, step = 0.1)))),

    conditionalPanel("input.a_engine == 'edger'",
      tags$details(
        tags$summary(tags$strong("edgeR options")),
        div(class = "ctl-block",
          radioButtons("a_edger_test", NULL,
                       choices = c("Quasi-likelihood F-test (recommended)" = "ql",
                                   "Likelihood-ratio test" = "lrt")),
          checkboxInput("a_edger_robust", "Robust dispersion / QL estimation", TRUE),
          numericInput("a_edger_lfc", "Test against |log2 FC| threshold (glmTreat)", 0, min = 0, step = 0.1)))),

    conditionalPanel("input.a_engine == 'ebseq'",
      div(class = "note-warn", style = "font-size:.85em",
        "EBSeq compares two groups at a time without covariates and reports posterior probabilities (PPDE) ",
        "instead of p-values. The adjusted-p column holds 1 \u2212 PPDE, so the sidebar's adjusted p \u2264 0.05 ",
        "means PPDE \u2265 0.95."),
      numericInput("a_ebseq_maxround", "EM iterations (maxround)", 5, min = 1, max = 50, step = 1)),

    tags$hr(),
    actionButton("a_run", "Run analysis", class = "btn-primary btn-block"),
    helpText("The app is busy while the analysis runs; a progress bar shows each step.")
  )
}

#' Main panel of the Analysis tab.
analysis_tab_ui <- function() {
  tagList(
    div(class = "note-ok", style = "font-size:.9em",
        "Run DESeq2, limma-voom, edgeR or EBSeq on genes or transcripts, or test transcript usage (DTU) with ",
        "edgeR / limma diffSplice, DEXSeq, DRIMSeq or satuRn, and explore the result in every other tab. ",
        "Results from tools run elsewhere still load on the Data tab."),

    h4("1. Count matrix"),
    fluidRow(
      column(6,
        fileInput("a_counts", "Raw counts, genes or transcripts \u00d7 samples (.tsv, .csv, .gz)",
                  accept = c(".tsv", ".txt", ".csv", ".gz")),
        conditionalPanel("input.a_level == 'gene'",
          helpText("For example salmon.merged.gene_counts.tsv, rsem.merged.gene_counts.tsv or featureCounts output. A gene_name column is recognised and kept for symbols.")),
        conditionalPanel("input.a_level != 'gene'",
          helpText("For example salmon.merged.transcript_counts.tsv or rsem.merged.transcript_counts.tsv (estimated counts, not TPM or scaled counts). A gene_id column becomes the transcript-to-gene map."),
          tags$details(open = NA,
            tags$summary(tags$strong("Or read the quantification folders (recommended)")),
            div(class = "ctl-block",
              helpText("One folder per sample: Salmon (quant.sf), kallisto (abundance.tsv) or RSEM (*.isoforms.results).",
                       "Gives counts, per-sample effective lengths and, with resamples, the quantification uncertainty."),
              textInput("a_quant_path", "Folder on this computer", placeholder = "e.g. ~/project/results/salmon"),
              fileInput("a_quant_zip", "or a .zip of that folder", accept = ".zip"),
              actionButton("a_quant_read", "Read quantifications", class = "btn-block"))),
          fileInput("a_tx2gene", "Transcript-to-gene map (optional: tx2gene table or GTF)",
                    accept = c(".tsv", ".txt", ".csv", ".gz", ".gtf", ".gff", ".gff3")))),
      column(6,
        fileInput("a_annot", "Gene annotation: GTF / GFF3 or an id\u2013symbol table (optional)",
                  accept = c(".gtf", ".gff", ".gff3", ".tsv", ".txt", ".csv", ".gz")),
        annotation_fetch_ui("a"),
        fileInput("a_lengths", "Lengths for TPM / FPKM and offsets (optional, e.g. rsem.merged.gene_lengths.tsv)",
                  accept = c(".tsv", ".txt", ".csv", ".gz")),
        helpText("A GTF, uploaded or downloaded, also supplies gene lengths and the transcript-to-gene map; a lengths file takes priority. For transcripts use effective lengths (read automatically from quantification folders)."),
        actionButton("a_use_example", "Use the bundled example (counts and its design)",
                     class = "btn-block"))),
    uiOutput("a_counts_note"),

    hr(),
    h4("2. Samples and variables"),
    uiOutput("a_include_ui"),
    fluidRow(
      column(6, fileInput("a_load_sheet", "Load a sample sheet (optional; CSV / TSV, e.g. a saved design)",
                          accept = c(".csv", ".tsv", ".txt"))),
      column(6, helpText(style = "margin-top:28px",
        "Matched to the count matrix by the 'sample' column. Its variables are added to (or replace) the ones below; extra columns such as FASTQ paths are ignored."))),
    sheet_editor_ui("a"),

    hr(),
    h4("3. Model and comparisons"),
    fluidRow(
      column(4,
        selectInput("a_main", "Main variable (compared)", choices = NULL),
        checkboxGroupInput("a_covars", "Covariates / blocking factors", choices = NULL),
        uiOutput("a_formula")),
      column(8,
        fluidRow(
          column(4, selectInput("a_ref", "Reference (denominator)", choices = NULL)),
          column(4, selectInput("a_target", "Target (numerator)", choices = NULL)),
          column(4, textInput("a_cmp_name", "Name (optional)", placeholder = "automatic"))),
        fluidRow(
          column(4, actionButton("a_add_cmp", "Add comparison", class = "btn-primary btn-block")),
          column(4, actionButton("a_all_vs_ref", "Every level vs reference", class = "btn-block")),
          column(4, actionButton("a_clear_cmp", "Clear all", class = "btn-block"))),
        DT::DTOutput("a_cmp_table"),
        actionButton("a_remove_cmp", "Remove selected comparisons"),
        fluidRow(style = "margin-top:10px",
          column(6, fileInput("a_load_contrasts", "Load comparisons (contrasts CSV)", accept = c(".csv", ".tsv", ".txt"))),
          column(6, br(), tags$label("Save this design"), br(),
                 downloadButton("a_dl_sheet", "Sample sheet", class = "btn-sm"),
                 downloadButton("a_dl_contrasts", "Comparisons", class = "btn-sm"))),
        helpText("Saved as two CSV files: the sample sheet, and the comparisons (id, variable, reference, target, blocking). Both load back here."))),
    uiOutput("a_checks"),

    hr(),
    h4("4. Results"),
    uiOutput("a_result_note"),
    DT::DTOutput("a_result_table"),
    fluidRow(
      column(4, selectInput("a_explore_cmp", "Comparison", choices = NULL)),
      column(3, br(), actionButton("a_explore", "Explore this comparison", class = "btn-primary btn-block")),
      column(3, br(), downloadButton("a_dl_result", "All genes (TSV)", class = "btn-block")),
      column(2, br(), downloadButton("a_dl_sig", "Significant (TSV)", class = "btn-block"))),
    fluidRow(
      column(4, downloadButton("a_dl_bundle", "Everything (zip)", class = "btn-primary btn-block")),
      column(4, downloadButton("a_dl_script", "R script to reproduce", class = "btn-block")),
      column(4, downloadButton("a_dl_record", "Run record (Markdown)", class = "btn-block"))),
    helpText("The zip holds every comparison's results, normalised and transformed matrices, QC figures, the sample sheet and comparisons, the run record and an R script that repeats the run from those files."),
    tags$details(tags$summary(tags$strong("Run record")), uiOutput("a_record")),
    uiOutput("a_usage_ui"),

    hr(),
    h4("5. Quality control"),
    uiOutput("a_qc_note"),
    fluidRow(
      column(3, selectInput("a_qc_which", "Plot", choices = QC_PLOTS)),
      column(3, conditionalPanel("input.a_qc_which == 'pca' || input.a_qc_which == 'distance'",
        selectInput("a_qc_colour", "Colour / annotate by", choices = NULL))),
      column(3,
        conditionalPanel("input.a_qc_which == 'pca'",
          selectInput("a_qc_shape", "Shape by", choices = NULL)),
        conditionalPanel("input.a_qc_which == 'pvalues'",
          selectizeInput("a_qc_cmps", "Comparisons", choices = NULL, multiple = TRUE))),
      column(3, conditionalPanel("input.a_qc_which == 'pca'",
        numericInput("a_qc_ntop", "Most variable genes", 500, min = 50, max = 50000, step = 50)))),
    plotOutput("a_qc_plot", height = "580px"),
    fluidRow(
      column(2, numericInput("a_qc_w", "Width (in)", 8, min = 2, max = 30, step = 0.5)),
      column(2, numericInput("a_qc_h", "Height (in)", 6, min = 2, max = 30, step = 0.5)),
      column(2, numericInput("a_qc_dpi", "DPI", 300, min = 72, max = 1200, step = 1)),
      column(2, br(), downloadButton("a_qc_dl_png", "PNG", class = "btn-block")),
      column(2, br(), downloadButton("a_qc_dl_pdf", "PDF", class = "btn-block")),
      column(2, br(), downloadButton("a_qc_dl_tiff", "TIFF", class = "btn-block"))),
    h5("Per-sample summary"),
    DT::DTOutput("a_qc_table")
  )
}
